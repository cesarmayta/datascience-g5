# TIPOS DE DATOS
# PROGRAMA QUE SUMA 2 NÚMEROS
# ENTRADA
numero1 = input("Ingrese el primer número :")
numero2 = input("Ingrese el segundo número : ")
# PROCESO
numero1 = int(numero1)
numero2 = int(numero2)
suma = numero1 + numero2


print("TIPOS DE DATOS")
print(f" numero 1 : {type(numero1)}")
print(f" numero 2 : {type(numero2)}")
print(f" suma : {type(suma)}")
# SALIDA
print(f"La suma de {numero1} + {numero2} es {suma}")